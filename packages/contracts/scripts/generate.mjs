// Regenerates everything derived from the JSON Schemas:
//   generated/schemas/**           self-contained copies of every schema (what the API loads at runtime)
//   generated/ts/*.d.ts            TypeScript declarations
//   ../../services/engine/contracts/**  Pydantic models + registry.py
// Run with `npm run generate`; CI runs `npm run check` to fail when the committed output is stale.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import $RefParser from '@apidevtools/json-schema-ref-parser';
import { compile } from 'json-schema-to-typescript';

const DATAMODEL_CODEGEN_VERSION = '0.83.0';
const PY_HEADER = '# Generated by packages/contracts/scripts/generate.mjs. Do not edit.';
const TS_BANNER = '/* Generated by packages/contracts/scripts/generate.mjs. Do not edit. */';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemasOut = join(pkgRoot, 'generated', 'schemas');
const tsOut = join(pkgRoot, 'generated', 'ts');
const pyOut = join(pkgRoot, '..', '..', 'services', 'engine', 'contracts');
const posix = (p) => p.split('\\').join('/');
const hasDefs = (schema) => schema && Object.keys(schema.$defs ?? {}).length > 0;

const writeText = (file, text) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text.replace(/\r\n/g, '\n'));
};
const writeJson = (file, value) => writeText(file, JSON.stringify(value, null, 2) + '\n');
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));

rmSync(join(pkgRoot, 'generated'), { recursive: true, force: true });
rmSync(pyOut, { recursive: true, force: true });

// 1. Schemas -------------------------------------------------------------------------------------
const sources = []; // paths relative to pkgRoot, e.g. usecases/system/events.schema.json
const collect = (rel) => {
  for (const entry of readdirSync(join(pkgRoot, rel), { withFileTypes: true })) {
    const child = posix(join(rel, entry.name));
    if (entry.isDirectory()) {
      if (entry.name !== 'examples') collect(child);
    } else if (entry.name.endsWith('.schema.json')) {
      sources.push(child);
    } else if (rel.startsWith('usecases/') && (entry.name === 'usecase.json' || entry.name === 'metrics.json')) {
      cpSync(join(pkgRoot, child), join(schemasOut, child));
    }
  }
};
for (const top of ['common', 'envelope', 'usecases']) collect(top);

const bundled = new Map(); // rel source path -> bundled schema
for (const rel of sources.sort()) {
  const schema = await $RefParser.bundle(join(pkgRoot, rel));
  bundled.set(rel, schema);
  writeJson(join(schemasOut, rel.replace(/\.schema\.json$/, '.json')), schema);
}
// cpSync keeps source bytes; normalise the copied files like everything else
for (const rel of ['usecase.json', 'metrics.json']) {
  for (const id of readdirSync(join(pkgRoot, 'usecases'))) {
    const file = join(schemasOut, 'usecases', id, rel);
    if (existsSync(file)) writeJson(file, readJson(file));
  }
}

// 2. TypeScript ----------------------------------------------------------------------------------
const pascal = (s) => s.replace(/(^|[_-])(\w)/g, (_, __, c) => c.toUpperCase());
const toTs = async (schema, name) =>
  compile(schema, name, { bannerComment: '', unreachableDefinitions: true, additionalProperties: false });

const useCases = readdirSync(join(pkgRoot, 'usecases'), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const envelopeTs = await toTs(bundled.get('envelope/message.schema.json'), 'Message');
writeText(join(tsOut, 'envelope.d.ts'), `${TS_BANNER}\n\n${envelopeTs}`);
for (const id of useCases) {
  const parts = [];
  for (const file of ['settings', 'events', 'intervals']) {
    const schema = bundled.get(`usecases/${id}/${file}.schema.json`);
    if (schema && (file === 'settings' || hasDefs(schema))) parts.push(await toTs(schema, pascal(`${id}_${file}`)));
  }
  writeText(join(tsOut, `${id}.d.ts`), `${TS_BANNER}\n\n${parts.join('\n')}`);
}
writeText(
  join(tsOut, 'index.d.ts'),
  [TS_BANNER, '', "export * from './envelope';", ...useCases.map((id) => `export * as ${id} from './${id}';`), ''].join('\n'),
);

// 3. Pydantic ------------------------------------------------------------------------------------
const codegen = (input, output) => {
  mkdirSync(dirname(output), { recursive: true });
  execFileSync(
    'uvx',
    [
      '--from', `datamodel-code-generator==${DATAMODEL_CODEGEN_VERSION}`,
      'datamodel-codegen',
      '--input', input,
      '--input-file-type', 'jsonschema',
      '--output', output,
      '--output-model-type', 'pydantic_v2.BaseModel',
      '--use-title-as-name',
      '--formatters', 'black', 'isort',
      '--disable-timestamp',
      '--target-python-version', '3.12',
      '--custom-file-header', PY_HEADER,
    ],
    { stdio: ['ignore', 'inherit', 'inherit'], env: { ...process.env, PYTHONWARNINGS: 'ignore::FutureWarning' } },
  );
  writeText(output, readFileSync(output, 'utf8')); // black writes CRLF on Windows; keep output byte-identical across OSes
};
const bundledPath = (rel) => join(schemasOut, rel.replace(/\.schema\.json$/, '.json'));

codegen(bundledPath('envelope/message.schema.json'), join(pyOut, 'envelope.py'));
writeText(join(pyOut, '__init__.py'), `${PY_HEADER}\n`);

const registryImports = [];
const registryEntries = [];
for (const id of useCases) {
  const base = `usecases/${id}`;
  const meta = readJson(join(pkgRoot, base, 'usecase.json'));
  const metrics = readJson(join(pkgRoot, base, 'metrics.json'));
  writeText(join(pyOut, id, '__init__.py'), `${PY_HEADER}\n`);

  const classesOf = (file) => {
    const schema = bundled.get(`${base}/${file}.schema.json`);
    if (!hasDefs(schema)) return null;
    codegen(bundledPath(`${base}/${file}.schema.json`), join(pyOut, id, `${file}.py`));
    return Object.entries(schema.$defs).map(([key, def]) => [key, def.title]);
  };

  const settingsSchema = bundled.get(`${base}/settings.schema.json`);
  if (settingsSchema) codegen(bundledPath(`${base}/settings.schema.json`), join(pyOut, id, 'settings.py'));
  const events = classesOf('events') ?? [];
  const intervals = classesOf('intervals') ?? [];

  const imp = (module, names) => names.length && registryImports.push(`from contracts.${id}.${module} import ${names.join(', ')}`);
  imp('settings', settingsSchema ? [settingsSchema.title] : []);
  imp('events', events.map(([, title]) => title));
  imp('intervals', intervals.map(([, title]) => title));

  const dict = (pairs) => (pairs.length ? `{${pairs.map(([k, v]) => `${JSON.stringify(k)}: ${v}`).join(', ')}}` : '{}');
  registryEntries.push(
    [
      `    ${JSON.stringify(id)}: UseCaseContract(`,
      `        label=${JSON.stringify(meta.label)},`,
      `        schema_version=${meta.schemaVersion},`,
      `        settings=${settingsSchema ? settingsSchema.title : 'None'},`,
      `        events=${dict(events)},`,
      `        intervals=${dict(intervals)},`,
      `        metrics=${dict(Object.entries(metrics).map(([name, m]) => [name, JSON.stringify(m.unit)]))},`,
      '    ),',
    ].join('\n'),
  );
}

writeText(
  join(pyOut, 'registry.py'),
  [
    PY_HEADER,
    'from __future__ import annotations',
    '',
    'from dataclasses import dataclass',
    '',
    'from pydantic import BaseModel',
    '',
    ...registryImports,
    '',
    '',
    '@dataclass(frozen=True)',
    'class UseCaseContract:',
    '    label: str',
    '    schema_version: int',
    '    settings: type[BaseModel] | None',
    '    events: dict[str, type[BaseModel]]',
    '    intervals: dict[str, type[BaseModel]]',
    '    metrics: dict[str, str]  # name -> unit',
    '',
    '',
    'REGISTRY: dict[str, UseCaseContract] = {',
    ...registryEntries,
    '}',
    '',
  ].join('\n'),
);

console.log(`generated ${bundled.size} schemas, ${useCases.length} use cases (${relative(process.cwd(), pyOut) || '.'})`);
